def correr_epoca(model, loader, criterion, optimizer=None):
    entrenando = optimizer is not None
    model.train() if entrenando else model.eval()
    perdida_total, correctos, total = 0.0, 0, 0

    with torch.set_grad_enabled(entrenando):
        for imgs, labels in loader:
            imgs = imgs.to(device, non_blocking=True)
            labels = labels.to(device, non_blocking=True)
            if entrenando:
                optimizer.zero_grad(set_to_none=True)

            with torch.amp.autocast('cuda', enabled=amp_activo):
                outputs = model(imgs)
                loss = criterion(outputs, labels)

            if entrenando:
                scaler.scale(loss).backward()
                scaler.step(optimizer)
                scaler.update()

            perdida_total += loss.item() * imgs.size(0)
            _, preds = torch.max(outputs, 1)
            correctos += (preds == labels).sum().item()
            total += imgs.size(0)

    return perdida_total / total, correctos / total


def entrenar_modelo(model, optimizer, nombre_arq, train_loader, val_loader):
    """Entrenamiento reanudable: si existe checkpoint para esta
    arquitectura, continua donde quedo. Si ya termino antes, no
    reentrena, solo devuelve el historial y los mejores pesos ya
    guardados (util si vuelves a correr la celda por error)."""
    checkpoint_path = f"{MODELOS_DIR}/checkpoint_{nombre_arq}.pt"
    criterion = nn.CrossEntropyLoss()

    if Path(checkpoint_path).is_file():
        ck = torch.load(checkpoint_path, map_location=device)
        model.load_state_dict(ck["model_state"])
        optimizer.load_state_dict(ck["optimizer_state"])
        epoch_inicial = ck["epoch"] + 1
        historial = ck["historial"]
        mejor_val_loss = ck["mejor_val_loss"]
        mejor_pesos = ck["mejor_pesos"]
        epocas_sin_mejorar = ck["epocas_sin_mejorar"]
        tiempo_acumulado = ck.get("tiempo_acumulado", 0.0)
        print(f"[{nombre_arq}] Checkpoint encontrado, reanudando desde epoca {epoch_inicial + 1}")
    else:
        historial = {"train_loss": [], "train_acc": [], "val_loss": [], "val_acc": []}
        epoch_inicial = 0
        mejor_val_loss = float("inf")
        mejor_pesos = copy.deepcopy(model.state_dict())
        epocas_sin_mejorar = 0
        tiempo_acumulado = 0.0
        print(f"[{nombre_arq}] Sin checkpoint previo, entrenando desde cero")

    inicio = time.time()

    for epoch in range(epoch_inicial, EPOCHS):
        train_loss, train_acc = correr_epoca(model, train_loader, criterion, optimizer)
        val_loss, val_acc = correr_epoca(model, val_loader, criterion, optimizer=None)

        historial["train_loss"].append(train_loss)
        historial["train_acc"].append(train_acc)
        historial["val_loss"].append(val_loss)
        historial["val_acc"].append(val_acc)

        print(f"[{nombre_arq}] Epoca {epoch+1:2d}/{EPOCHS} | "
              f"train_loss={train_loss:.4f} train_acc={train_acc:.4f} | "
              f"val_loss={val_loss:.4f} val_acc={val_acc:.4f}")

        if val_loss < mejor_val_loss:
            mejor_val_loss = val_loss
            mejor_pesos = copy.deepcopy(model.state_dict())
            epocas_sin_mejorar = 0
        else:
            epocas_sin_mejorar += 1

        tiempo_acumulado_actual = tiempo_acumulado + (time.time() - inicio)

        es_ultima_epoca = epoch == EPOCHS - 1
        toca_checkpoint = ((epoch + 1) % CHECKPOINT_EVERY == 0)
        va_a_parar = epocas_sin_mejorar >= PATIENCE_EARLY_STOP

        if toca_checkpoint or es_ultima_epoca or va_a_parar:
            torch.save({
                "epoch": epoch, "model_state": model.state_dict(),
                "optimizer_state": optimizer.state_dict(), "historial": historial,
                "mejor_val_loss": mejor_val_loss, "mejor_pesos": mejor_pesos,
                "epocas_sin_mejorar": epocas_sin_mejorar,
                "tiempo_acumulado": tiempo_acumulado_actual,
            }, checkpoint_path)

        if va_a_parar:
            print(f"[{nombre_arq}] Early stopping en epoca {epoch+1}")
            break

    tiempo_total = tiempo_acumulado + (time.time() - inicio)
    model.load_state_dict(mejor_pesos)
    torch.save(model.state_dict(), f"{MODELOS_DIR}/mejor_{nombre_arq}.pt")

    return model, historial, tiempo_total


def graficar_historial(historial, nombre_arq):
    epochs_range = range(len(historial["train_loss"]))
    plt.figure(figsize=(12, 4))
    plt.suptitle(nombre_arq)

    plt.subplot(1, 2, 1)
    plt.plot(epochs_range, historial["train_acc"], label="Train")
    plt.plot(epochs_range, historial["val_acc"], label="Val")
    plt.legend(); plt.title("Accuracy")

    plt.subplot(1, 2, 2)
    plt.plot(epochs_range, historial["train_loss"], label="Train")
    plt.plot(epochs_range, historial["val_loss"], label="Val")
    plt.legend(); plt.title("Loss")

    plt.tight_layout()
    plt.show()


def evaluar_y_mostrar(model, test_loader, class_names, nombre_arq, tiempo_entrenamiento, guardar=True):
    model.eval()
    y_true, y_pred = [], []
    with torch.no_grad():
        for imgs, labels in test_loader:
            imgs = imgs.to(device)
            outputs = model(imgs)
            _, preds = torch.max(outputs, 1)
            y_true.extend(labels.numpy())
            y_pred.extend(preds.cpu().numpy())

    test_acc = (np.array(y_true) == np.array(y_pred)).mean()
    precision, recall, f1, _ = precision_recall_fscore_support(
        y_true, y_pred, average="macro", zero_division=0
    )
    num_params = sum(p.numel() for p in model.parameters())

    print(f"\n=== {nombre_arq} - RESULTADOS EN TEST ===")
    print(f"Accuracy:  {test_acc:.4f}")
    print(f"Precision (macro): {precision:.4f}")
    print(f"Recall (macro):    {recall:.4f}")
    print(f"F1 (macro):        {f1:.4f}")
    print(f"Parametros totales: {num_params:,}")
    print(f"Tiempo de entrenamiento: {tiempo_entrenamiento/60:.1f} min")
    print("\nReporte por clase:")
    print(classification_report(y_true, y_pred, target_names=class_names))

    cm = confusion_matrix(y_true, y_pred)
    plt.figure(figsize=(5, 4))
    sns.heatmap(cm, annot=True, fmt="d", cmap="Blues",
                xticklabels=class_names, yticklabels=class_names)
    plt.xlabel("Prediccion"); plt.ylabel("Real")
    plt.title(f"Matriz de confusion - {nombre_arq}")
    plt.show()

    if guardar:
        registrar_resultado(nombre_arq, test_acc, precision, recall, f1,
                             num_params, tiempo_entrenamiento)

    return test_acc, precision, recall, f1


def registrar_resultado(nombre_arq, accuracy, precision, recall, f1, num_params, tiempo_seg):
    """Agrega (o actualiza) la fila de esta arquitectura en el CSV
    comparativo compartido en Drive."""
    filas = {}
    if Path(RESULTADOS_CSV).is_file():
        with open(RESULTADOS_CSV, newline="", encoding="utf-8") as f:
            for row in csv.DictReader(f):
                filas[row["arquitectura"]] = row

    filas[nombre_arq] = {
        "arquitectura": nombre_arq,
        "accuracy": f"{accuracy:.4f}",
        "precision_macro": f"{precision:.4f}",
        "recall_macro": f"{recall:.4f}",
        "f1_macro": f"{f1:.4f}",
        "num_parametros": num_params,
        "tiempo_entrenamiento_min": f"{tiempo_seg/60:.1f}",
    }

    with open(RESULTADOS_CSV, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=list(next(iter(filas.values())).keys()))
        writer.writeheader()
        writer.writerows(filas.values())

    print(f"Resultado de '{nombre_arq}' guardado en {RESULTADOS_CSV}")

