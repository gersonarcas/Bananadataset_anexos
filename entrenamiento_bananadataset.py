def obtener_predicciones_correctas(nombre_arq, test_loader):
    modelo_path = f"{MODELOS_DIR}/mejor_{nombre_arq}.pt"
    checkpoint_path = f"{MODELOS_DIR}/checkpoint_{nombre_arq}.pt"

    # Reconstruir la arquitectura base
    if "SqueezeNet" in nombre_arq:
        modelo = models.squeezenet1_1()
        modelo.classifier[1] = nn.Conv2d(512, num_classes, kernel_size=1)
    elif "ResNet" in nombre_arq:
        modelo = models.resnet50()
        modelo.fc = nn.Linear(modelo.fc.in_features, num_classes)
    elif "EfficientNet" in nombre_arq:
        modelo = models.efficientnet_b0()
        modelo.classifier[1] = nn.Linear(modelo.classifier[1].in_features, num_classes)
    elif "DenseNet" in nombre_arq:
        modelo = models.densenet121()
        modelo.classifier = nn.Linear(modelo.classifier.in_features, num_classes)
    else:
        raise ValueError(f"Arquitectura {nombre_arq} no reconocida")

    # Cargar los mejores pesos
    modelo.load_state_dict(torch.load(modelo_path, map_location=device))
    modelo = modelo.to(device)
    modelo.eval()

    aciertos = []
    with torch.no_grad():
        for imgs, labels in test_loader:
            imgs = imgs.to(device)
            outputs = modelo(imgs)
            _, preds = torch.max(outputs, 1)
            # Guardamos un array booleano de si acertó (True) o no (False)
            aciertos.extend((preds.cpu() == labels).numpy())
    return np.array(aciertos)

